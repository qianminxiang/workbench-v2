/// 精确区县名 → 地市。输入带不带「区/县/市」后缀都可以
/// （"凤台县"/"凤台" 都命中淮南市）。同名歧义（不存在于当前表）返回首个命中。
pub fn district_to_city(name: &str) -> Option<&'static str> {
    let n = name.trim();
    if n.is_empty() {
        return None;
    }
    for (d, c) in DISTRICTS {
        if *d == n {
            return Some(c);
        }
    }
    // 去后缀短名匹配（短名 ≥2 字，避免单字误伤，如「和」）
    let stripped = n.trim_end_matches(['区', '县', '市']);
    if stripped.chars().count() >= 2 {
        for (d, c) in DISTRICTS {
            if d.trim_end_matches(['区', '县', '市']) == stripped {
                return Some(c);
            }
        }
    }
    None
}

/// 在一段自由文本（公司名 / 地址 / 区域字段拼接）里定位区县。
/// 返回 (命中的规范区县名, 所属地市)。多个命中时取**最靠前**的
/// （地址里排前面的通常是主体所在区县）。
pub fn locate_in_text(text: &str) -> Option<(&'static str, &'static str)> {
    for (d, c) in DISTRICTS {
        if text.contains(d) {
            return Some((d, c));
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_county_to_city_pairs() {
        assert_eq!(district_to_city("凤台县"), Some("淮南市"));
        assert_eq!(district_to_city("太湖县"), Some("安庆市"));
        assert_eq!(district_to_city("寿县"), Some("淮南市"));
        assert_eq!(district_to_city("巢湖市"), Some("合肥市"));
        assert_eq!(district_to_city("无为"), Some("芜湖市")); // 短名
        assert_eq!(district_to_city("不存在县"), None);
        assert_eq!(district_to_city(""), None);
    }

    #[test]
    fn locate_from_free_text() {
        let n = locate_in_text("凤台县农兴农业服务有限公司 安徽省淮南市凤台县");
        assert_eq!(n, Some(("凤台县", "淮南市")));
        let n2 = locate_in_text("安庆市太湖县晋熙镇某某合作社");
        assert_eq!(n2, Some(("太湖县", "安庆市")));
        assert_eq!(locate_in_text("某某科技有限公司（外省）"), None);
    }

    #[test]
    fn every_district_maps_to_a_known_city() {
        for (d, c) in DISTRICTS {
            assert!(CITIES.contains(c), "{d} 的地市 {c} 不在 16 市列表里");
            assert_eq!(district_to_city(d), Some(*c), "{d} 自身应当命中 {c}");
        }
    }
}
